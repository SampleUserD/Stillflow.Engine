// scripts/gen-tags.ts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'

function extractKeys(dts: string, interfaceName: string): string[] {
  // ищем `interface Name { ... }` с балансировкой скобок
  const start = dts.indexOf(`interface ${interfaceName}`)
  if (start === -1) throw new Error(`${interfaceName} not found in lib.dom.d.ts`)

  const braceOpen = dts.indexOf('{', start)
  let depth = 0
  let braceClose = -1
  for (let i = braceOpen; i < dts.length; i++) {
    if (dts[i] === '{') depth++
    else if (dts[i] === '}') {
      depth--
      if (depth === 0) { braceClose = i; break }
    }
  }
  if (braceClose === -1) throw new Error(`Unbalanced braces in ${interfaceName}`)

  const body = dts.slice(braceOpen + 1, braceClose)
  // ключи в мапе — это строковые литералы: "div": HTMLDivElement;
  return [...body.matchAll(/"([^"]+)"\s*:/g)].map(m => m[1])
}

const dtsPath = resolve('node_modules/@typescript/typescript-win32-x64/lib/lib.dom.d.ts')
const dts = readFileSync(dtsPath, 'utf8')

const html = extractKeys(dts, 'HTMLElementTagNameMap')
const svg = extractKeys(dts, 'SVGElementTagNameMap')
const math = extractKeys(dts, 'MathMLElementTagNameMap')

const out = `// AUTO-GENERATED by scripts/gen-tags.ts. Do not edit.
// Source: typescript/lib/lib.dom.d.ts

export const HTML_TAGS = ${JSON.stringify(html)} as const
export const SVG_TAGS  = ${JSON.stringify(svg)} as const
export const MATH_TAGS = ${JSON.stringify(math)} as const

export type HTMLTag = typeof HTML_TAGS[number]
export type SVGTag  = typeof SVG_TAGS[number]
export type MathTag = typeof MATH_TAGS[number]

export type Tag = HTMLTag | SVGTag | MathTag
`

const outPath = resolve('src/fabrics/dom/tags.ts')
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, out)

console.log(`Generated: ${html.length} HTML, ${svg.length} SVG, ${math.length} MathML tags`)